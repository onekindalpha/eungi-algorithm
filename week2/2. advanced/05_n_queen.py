"""
[백트래킹 - N-Queen]

▣ 문제 배경
1848년 독일의 체스 마스터 Max Bezzel 이 처음 제시하고, 이듬해 Franz Nauck 가
임의의 N 으로 일반화한 고전 퍼즐입니다. 저작권이 만료된 퍼블릭 도메인 문제이며,
본 지문과 테스트 케이스는 이 학습 자료를 위해 자체적으로 작성되었습니다.

▣ 상황 설명
N x N 크기의 정사각형 체스판이 주어집니다.
체스의 퀸(Queen) 은 같은 행, 같은 열, 그리고 두 대각선 방향으로
임의의 칸 만큼 이동/공격할 수 있는 강력한 기물입니다.

▣ 목표
N 개의 퀸을 서로 공격할 수 없도록 N x N 체스판 위에 배치하는
서로 다른 배치의 수를 구하세요.

▣ 작은 예시 (N = 4)
서로 공격하지 않는 배치는 정확히 다음 두 가지뿐입니다 (좌우 대칭).
'Q' = 퀸이 놓인 칸, '.' = 빈 칸

    배치 A           배치 B
    . Q . .          . . Q .
    . . . Q          Q . . .
    Q . . .          . . . Q
    . . Q .          . Q . .

▣ 구현할 함수
n_queens(n: int) -> int
  - N x N 체스판에 N 개의 퀸을 서로 공격하지 않게 배치하는 경우의 수를 반환.
  - 1 <= N <= 8 범위 내에서 동작하면 충분합니다.

▣ 기대 결과 (참고)
N = 1 -> 1       (단 한 칸, 퀸 한 개)
N = 2 -> 0       (두 퀸이 항상 서로 공격함)
N = 3 -> 0
N = 4 -> 2
N = 5 -> 10
N = 6 -> 4
N = 7 -> 40
N = 8 -> 92      (전통적인 "8-Queens 문제" 의 답)

▣ 제약
- 1 <= N <= 8

▣ 힌트 (백트래킹 아이디어)
- 각 행에는 정확히 하나의 퀸만 놓을 수 있으므로, 1차원 배열 cols 를 사용해
    cols[row] = 그 행에 놓은 퀸의 열 번호
  로 표현하면 충분합니다.
- row 행에 후보 열 c 를 두려고 할 때, 이전에 둔 모든 (i, cols[i]) 와의
  충돌을 검사합니다.
    같은 열 충돌  :  cols[i] == c
    대각선 충돌    :  abs(cols[i] - c) == row - i
- row 가 N 에 도달했다는 것은 모든 행을 무사히 채웠다는 의미이므로 1가지 경우.
"""


def n_queens(n: int) -> int:
    """
    N x N 체스판에 N 개의 퀸을 서로 공격하지 않도록 배치하는 경우의 수를 반환.
    1 <= N <= 8 범위에서 동작하면 충분합니다.
    """
    # TODO: 백트래킹으로 가능한 배치의 수를 반환하세요.
    # 권장 구조:
    cols = [0] * n
    # 가능한 배치의 수
    count = 0
    # 유효한지 여부
    valid = True
    # 언제 종료할 것인지
    # 유망함수
    def promising(row, c):
      for i in range(row):
        # 지금까지의 행 인덱스에 대한 열 인덱스가 현재 c인덱스와 같게 되면
        if cols[i] == c:
          valid = False
          return False
        # 만약 대각선에 이전에 놓인 퀸들이 있다면
        # 이전에 놓인 행 인덱스에 대한 열 인덱스와 현재 c인덱스의 차이가
        # 현재 행과 이전 행에 대한 차이가 같게 되면
        if abs(cols[i] - c) == row - i:
          valid = False
          return False
      return True
    # 열별로 c열을 놓는것이 가능한지 보겠다. 
    # place 함수
    def place(row):
      nonlocal count
      for c in range(n):
          # 만약 현재 행에 c열을 배치하는 것이 유망하면
          if promising(row, c):
              # cols[row인덱스]는 c열 인덱스를 기입한다. 
              cols[row] = c
              # 그리고 다른 행에 대해서도 c열 인덱스를 찾아서 기입한다. 
              place(row + 1)
      # 만약 모든 행에 퀸을 배치했으면 완성된 배치 하나를 찾았으니 count를 1 증가시키고 돌아감. 
      if row == n:
        count+=1
        return
    # 초기호출을 한다. 
    place(0)
    return count


if __name__ == "__main__":
    print("[테스트] N=1 ~ N=8 에 대한 가능한 배치의 수")
    for n in range(1, 9):
        print(f"  N={n}: {n_queens(n)}")
